// test/tools/retired-test-paths.mjs — generates brain/scripts/lib/retired-test-paths.mjs (#1076).
//
// Repo-only tooling: not in package.json `files`, never shipped. Usage:
//   node test/tools/retired-test-paths.mjs          # rewrite the module
//   node test/tools/retired-test-paths.mjs --check  # exit 1 when the module is stale
//   npm run retired:test-paths
//
// The list is the union, over every published release tag, of the paths under
// brain/scripts/ that are test infrastructure. Only released tags: a suite that
// never shipped has nothing to prune, and a list that followed HEAD would drift
// every time a suite is added.

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const OUT = 'brain/scripts/lib/retired-test-paths.mjs';

/** Test-only helper modules with no runtime importer (verified #1076). `lib/tmp-tree.mjs` is runtime and is NOT here. */
const HELPERS = new Set([
  'brain/scripts/lib/hermetic-box.mjs',
  'brain/scripts/lib/test-brain-home.mjs',
  'brain/scripts/lib/test-tmp.mjs',
  'brain/scripts/test-hygiene.mjs',
]);
const TEST_DIRS = new Set(['__fixtures__', 'test-support', 'fixtures']);

/** Is `rel` test infrastructure under the managed `brain/scripts/**` glob? */
export function isTestInfraPath(rel) {
  if (!rel.startsWith('brain/scripts/')) return false;
  if (/\.test\.(m?js|cjs)$/.test(rel)) return true;
  if (HELPERS.has(rel)) return true;
  return rel.split('/').slice(0, -1).some((seg) => TEST_DIRS.has(seg));
}

const git = (cwd, args) => execFileSync('git', args, { cwd, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });

/**
 * Did the package built from this `package.json` text ship test suites? A release whose `files`
 * negates `brain/scripts/**\/*.test.mjs` (#1076, from 1.13.0) shipped none, so its repo tree must
 * not feed the prune list (#1389). Unreadable text counts as shipping, the conservative side.
 */
export function shipsTests(pkgText) {
  try {
    const files = JSON.parse(pkgText)?.files;
    return !(Array.isArray(files) && files.includes('!brain/scripts/**/*.test.mjs'));
  } catch {
    return true;
  }
}

/** Release tags `v1.x` whose package shipped tests, oldest first. */
export function publishedTags(cwd = ROOT) {
  const showPkg = (tag) => {
    try { return git(cwd, ['show', `${tag}:package.json`]); } catch { return null; }
  };
  return git(cwd, ['tag', '--list', 'v1.*']).split('\n').filter(Boolean)
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }))
    .filter((tag) => shipsTests(showPkg(tag)));
}

/** Sorted union of test-infrastructure paths across `tags`. */
export function generateList(cwd, tags) {
  const all = new Set();
  for (const tag of tags) {
    for (const rel of git(cwd, ['ls-tree', '-r', '--name-only', tag, '--', 'brain/scripts']).split('\n')) {
      if (rel && isTestInfraPath(rel)) all.add(rel);
    }
  }
  return [...all].sort();
}

export function renderModule(paths, tags) {
  return `// brain/scripts/lib/retired-test-paths.mjs — GENERATED. Do not edit by hand (issue #1076).
//
// Test infrastructure earlier releases shipped under the managed \`brain/scripts/**\`
// COPY glob and no longer do: \`*.test.mjs\`, \`__fixtures__\`, \`test-support\`,
// \`fixtures\` and the four test-only helper modules (package.json \`files\` excludes
// them). \`retired-paths.mjs\` folds this list into RETIRED_PATHS, which is the only
// thing the consumer's installed (older) upgrader reads.
//
// Generated by \`npm run retired:test-paths\` (test/tools/retired-test-paths.mjs):
// the union of matching paths in the trees of ${tags[0]}..${tags[tags.length - 1]} (${tags.length} release tags).
// Verified by test/retired-test-paths.e2e.test.mjs, which regenerates it from the tags.

export const RETIRED_TEST_PATHS = Object.freeze([
${paths.map((p) => `  '${p}',`).join('\n')}
]);
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const tags = publishedTags();
  const next = renderModule(generateList(ROOT, tags), tags);
  if (process.argv.includes('--check')) {
    let cur = '';
    try { cur = readFileSync(join(ROOT, OUT), 'utf8'); } catch { /* swallow-ok: missing file is stale */ }
    if (cur !== next) { console.error(`${OUT} is stale — run \`npm run retired:test-paths\``); process.exit(1); }
  } else {
    writeFileSync(join(ROOT, OUT), next);
    console.log(`wrote ${OUT}`);
  }
}
